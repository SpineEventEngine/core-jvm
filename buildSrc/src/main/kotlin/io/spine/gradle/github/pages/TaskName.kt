package io.spine.gradle.github.pages

object TaskName {

    /**
     * The name of the task that publishes the API documentation of a project.
     */
    const val publishApiDocs = "publishApiDocs"

    /**
     * The name of the task of the root project that publishes the API documentation
     * of all the published projects of the build.
     */
    const val publishAllApiDocs = "publishAllApiDocs"

    /**
     * The name of the helper task to gather the Javadoc format documentation
     * generated by Dokka before publishing it to GitHub Pages.
     */
    const val copyJavadocDocs = "copyJavadocDocs"

    /**
     * The name of the helper task to gather HTML documentation
     * generated by Dokka before publishing it to GitHub Pages.
     */
    const val copyHtmlDocs = "copyHtmlDocs"
}
